"""The identity of a Cube: its serial number, never its network address.

The address of a Cube changes (DHCP, a new router, a Cube that starts without a lease and answers
from its factory address), the serial number printed on it does not. Everything that identifies a
Cube therefore uses the serial number: the unique id of the config entry, the title shown in the
integration list and the identifier of the hub device. See docs/IDENTITY.md.
"""

from __future__ import annotations

import re

from .const import TITLE_PREFIX

# "MAX! Cube (192.168.10.60)" is what versions up to 1.3.2 generated; "MAX! Cube KEQ0523864" is the new form.
_GENERATED_TITLE = re.compile(rf"^{re.escape(TITLE_PREFIX)}( \(.*\)| [A-Z0-9]{{10}})?$")


def cube_title(serial: str) -> str:
    """Return the title of the config entry of the Cube with this serial number."""
    return f"{TITLE_PREFIX} {serial}"


def is_generated_title(title: str) -> bool:
    """Return True if the title was generated by the integration (not renamed by the user)."""
    return bool(_GENERATED_TITLE.match(title))
